let frame = 0;
function paint(progress, free) {
  landscape();
  dragon();
  princess(free);
  const x = 95 + 30 * progress;
  shape('#332530', [x - 17, 188, x + 9, 186, x + 15, 190, x + 6, 194, x - 14, 193]);
  const y = -5 + 193 * (progress ** 1.25);
  const angle = progress === 1 ? 0 : progress * Math.PI * 4;
  hero(x, y, angle);
}

export function playScene(onLand) {
  cancelAnimationFrame(frame);
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) {
    paint(1, false);
    onLand();
    return;
  }
  const start = performance.now();
  function tick(now) {
    const progress = Math.min(1, (now - start) / 1450);
    paint(progress, false);
    if (progress < 1) frame = requestAnimationFrame(tick);
    else onLand();
  }
  frame = requestAnimationFrame(tick);
}

export function freePrincess() {
  cancelAnimationFrame(frame);
  paint(1, true);
}
